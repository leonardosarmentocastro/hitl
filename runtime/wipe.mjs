#!/usr/bin/env node
// The feature's documents in no-install mode: the files under docs/superpowers/ that exist at a
// tip and not at its merge-base with the record's base. `archive` copies them to
// `<memoryDir>/features/<created>-<topic>/`; `build` also rebuilds `<feature branch>-wipe` as
// exactly one commit over its parent that deletes them, force-pushes that branch (the only one
// it ever pushes) and creates or retargets its draft PR through the PR shim. The commit is made
// with a temporary index: the working tree and the checked-out branch are never touched.
// CLI: archive | build. Exit: 0 ok · 1 usage · 2 error · 3 refused.
import { execFileSync, spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  realpathSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { emit, parseArgs } from "../installer/lib.mjs";
import { memoryDir } from "./memory.mjs";
import { getRecord } from "./session.mjs";

const DOCS = "docs/superpowers/";
export const WIPE_MESSAGE = "chore(docs): wipe transient superpowers artifacts [skip ci]";
export const WIPE_BODY = `Generated by hitl — do not edit; it is rebuilt on every run.

It deletes this feature's specs, plans and handover from the branch. They are transient: the
PR descriptions are the record. Merge this **last** — after every slice, and before the
umbrella PR. Fix-up rounds happen before it merges.
`;

class Failure extends Error {}

function git(repo, args, env = process.env) {
  try {
    return execFileSync("git", args, {
      cwd: repo,
      env,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      maxBuffer: 64 * 1024 * 1024,
    }).trim();
  } catch (e) {
    const why = String(e?.stderr ?? "").trim() || String(e?.message ?? e);
    throw new Failure(`git ${args[0]} failed: ${why}`);
  }
}

function docsAt(repo, rev) {
  return git(repo, ["ls-tree", "-r", "--name-only", rev, "--", DOCS]).split("\n").filter(Boolean);
}

/** Paths under docs/superpowers/ at `tip` that are not at its merge-base with `base`; sorted. */
export function featureDocs(repo, tip, base) {
  const mb = git(repo, ["merge-base", tip, base]);
  const before = new Set(docsAt(repo, mb));
  return docsAt(repo, tip)
    .filter((p) => !before.has(p))
    .sort();
}

/**
 * Make `dest` hold exactly `files` as they are at `tip`, relative to docs/superpowers/. The copy
 * is written to a sibling temp folder and renamed into place, so a failure leaves `dest` as it was.
 */
export function archiveDocs(repo, tip, files, dest) {
  mkdirSync(dirname(dest), { recursive: true });
  const staging = mkdtempSync(`${dest}.tmp-`);
  try {
    for (const f of files) {
      const content = execFileSync("git", ["show", `${tip}:${f}`], {
        cwd: repo,
        stdio: ["ignore", "pipe", "pipe"],
        maxBuffer: 64 * 1024 * 1024,
      });
      const out = join(staging, f.startsWith(DOCS) ? f.slice(DOCS.length) : f);
      mkdirSync(dirname(out), { recursive: true });
      writeFileSync(out, content);
    }
    rmSync(dest, { recursive: true, force: true });
    renameSync(staging, dest);
  } catch (e) {
    rmSync(staging, { recursive: true, force: true });
    throw e;
  }
}

/** A commit over `parentTip` whose tree is the parent's minus `files`; returns its sha. */
export function wipeCommit(repo, parentTip, files) {
  const dir = mkdtempSync(join(tmpdir(), "hitl-wipe-index-"));
  const env = { ...process.env, GIT_INDEX_FILE: join(dir, "index") };
  try {
    const parent = git(repo, ["rev-parse", "--verify", `${parentTip}^{commit}`]);
    git(repo, ["read-tree", parent], env);
    if (files.length > 0) git(repo, ["update-index", "--force-remove", "--", ...files], env);
    const tree = git(repo, ["write-tree"], env);
    return git(repo, ["commit-tree", tree, "-p", parent, "-m", WIPE_MESSAGE], env);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function archiveFolder(repo, record) {
  return join(memoryDir(repo), "features", `${record.created}-${record.topic}`);
}

function branchOf(base) {
  return base.startsWith("origin/") ? base.slice("origin/".length) : base;
}

function shim(path, args) {
  const r = spawnSync(path, args, { encoding: "utf8" });
  if (r.status !== 0 && !(args[0] === "create" && r.status === 3)) {
    const why = (r.stderr || r.error?.message || `exit ${r.status}`).trim();
    throw new Failure(`the PR shim failed (${args[0]}): ${why}`);
  }
  try {
    return JSON.parse(r.stdout);
  } catch {
    throw new Failure(`the PR shim printed something that is not JSON (${args[0]})`);
  }
}

function archive(args) {
  const record = getRecord(args.repo);
  if (!record) return { code: 3, out: { refused: "no-record" } };
  const files = featureDocs(args.repo, "HEAD", record.base);
  if (files.length === 0) return { code: 0, out: { status: "nothing-to-archive" } };
  const dest = archiveFolder(args.repo, record);
  archiveDocs(args.repo, "HEAD", files, dest);
  return { code: 0, out: { status: "archived", archive: dest, files } };
}

function build(args) {
  const { repo, parent } = args;
  const b = args["feature-branch"];
  const record = getRecord(repo);
  if (!record) return { code: 3, out: { refused: "no-record" } };
  const wipe = `${b}-wipe`;
  if (
    b === branchOf(record.base) ||
    parent === wipe ||
    !(parent === b || parent.startsWith(`${b}-`))
  )
    return { code: 3, out: { refused: "bad-branch" } };

  const remoteRef = `refs/remotes/origin/${parent}`;
  const hasRemote =
    spawnSync("git", ["-C", repo, "rev-parse", "--verify", "--quiet", `${remoteRef}^{commit}`])
      .status === 0;
  const parentTip = git(repo, [
    "rev-parse",
    "--verify",
    `${hasRemote ? remoteRef : `refs/heads/${parent}`}^{commit}`,
  ]);
  const files = featureDocs(repo, parentTip, record.base);
  const prs = shim(args.shim, ["list", "--head-prefix", wipe, "--state", "all"]).filter(
    (p) => p.head === wipe,
  );
  if (files.length === 0) {
    const merged = prs.find((p) => p.state === "merged");
    return {
      code: 0,
      out: merged ? { status: "merged", pr: merged.number } : { status: "nothing-to-wipe" },
    };
  }
  if (args["no-push"])
    return { code: 0, out: { status: "would-build", branch: wipe, parent, files } };

  const dest = archiveFolder(repo, record);
  archiveDocs(repo, parentTip, files, dest);
  const sha = wipeCommit(repo, parentTip, files);
  git(repo, ["update-ref", `refs/heads/${wipe}`, sha]);
  git(repo, ["push", "--force", "--quiet", "origin", `refs/heads/${wipe}:refs/heads/${wipe}`]);

  let pr = prs.find((p) => p.state === "open") ?? null;
  if (!pr) {
    const dir = mkdtempSync(join(tmpdir(), "hitl-wipe-body-"));
    try {
      const body = join(dir, "body.md");
      writeFileSync(body, WIPE_BODY);
      pr = shim(args.shim, [
        "create",
        "--draft",
        "--base",
        parent,
        "--head",
        wipe,
        "--title",
        `Wipe transient docs: ${b}`,
        "--body-file",
        body,
      ]);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }
  if (pr.base !== parent) pr = shim(args.shim, ["retarget", String(pr.number), "--base", parent]);
  return { code: 0, out: { status: "built", branch: wipe, pr: pr.number, archive: dest, files } };
}

const USAGE =
  "usage: archive --repo <worktree> | build --repo <worktree> --feature-branch <b> --parent <branch> --shim <path> [--no-push]";

export function run(verb, args) {
  const usage = { code: 1, out: { error: USAGE } };
  if (!args?.repo || !["archive", "build"].includes(verb)) return usage;
  if (verb === "build" && (!args["feature-branch"] || !args.parent || !args.shim)) return usage;
  try {
    return verb === "archive" ? archive(args) : build(args);
  } catch (e) {
    return { code: 2, out: { error: String(e?.message ?? e) } };
  }
}

// Compare realpaths: Node resolves symlinks in import.meta.url but not in argv[1].
const isMain =
  process.argv[1] !== undefined &&
  existsSync(process.argv[1]) &&
  realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));

if (isMain) emit(run(process.argv[2], parseArgs(process.argv.slice(3), ["no-push"])));
